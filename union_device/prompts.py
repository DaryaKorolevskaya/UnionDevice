def build_user_prompt(v: ValidatedInput) -> str:
    p = v.product
    payload = {
        "name": p.name,
        "manufacturer": p.manufacturer or None,
        "specs": p.specs,
        "description": p.description or None,
    }
    missing = ", ".join(v.missing_specs) if v.missing_specs else "нет"
    return (
        "<product>\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}\n"
        "</product>\n\n"
        f"Во входных данных отсутствуют характеристики: {missing}.\n"
        "Сформируй черновик карточки по правилам."
    )


def build_repair_prompt(problems: List[str]) -> str:
    bullet = "\n".join(f"- {p}" for p in problems)
    return (
        "Черновик не прошёл автоматическую проверку:\n"
        f"{bullet}\n\n"
        "Исправь только указанные проблемы и верни полный черновик заново. "
        "Если в тексте есть значение, которого нет во входных данных, — удали его, а не заменяй другим."
    )
